# Fonction d'importation des fichiers GaitRite
def importfile_GaitRite(filename):
    # Ouvrir le fichier et le lire

    fileID = open(filename, 'r')
    d = np.loadtxt(fileID, delimiter=',')
    fileID.close()

    # Décryptage des colonnes
    t = d[:, 1]
    foot = d[:, 2]
    x = d[:, 3]
    y = d[:, 4]

    # Exo, le tableau de sortie avec les pas
    ind = np.where(t == 0)[0]

    debut = []
    fin = []

    for i in range(len(ind) - 1):
        if ind[i + 1] == ind[i] + 1:
            debut.append(ind[i + 1] + 1)
            fin.append(ind[i] - 1)

    fin = np.append(fin[1:], len(t) - 1)  # On retire le premier qui vaut -1 et on ajoute le dernier

    t_debut = []
    t_fin = []

    for i in range(len(debut)):
        t_debut.append(t[debut[i]])
        t_fin.append(t[fin[i]])

    exo = []

    for i in range(len(debut)):
        exo.append([t_debut[i], t_fin[i], debut[i], fin[i], foot[debut[i]]])

    return x, y, exo, t


